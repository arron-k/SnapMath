export function curriculumMapText(): string {
  return Object.entries(curriculumMap)
    .map(([key, units]) => {
      const [grade, semester] = key.split("-");
      return `- ${grade}학년 ${semester}학기: ${units.join(", ")}`;
    })
    .join("\n");
}
